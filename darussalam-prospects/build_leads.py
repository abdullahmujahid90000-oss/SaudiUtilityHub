def build(path):
    wb = Workbook()
    ws = wb.active
    ws.title = "Leads"
    ws.append(HEADERS)
    for row in sorted(LEADS, key=lambda r: "ABC".index(r[0])):
        ws.append(list(row))

    fills = {"A": "C6EFCE", "B": "FFEB9C", "C": "F2F2F2"}
    widths = [9, 34, 48, 44, 38, 34, 32, 46]
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    for cell in ws[1]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor="1F4E78")
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")
        row[0].fill = PatternFill("solid", fgColor=fills[row[0].value])
        row[0].font = Font(bold=True)
    ws.freeze_panes = "C2"
    ws.auto_filter.ref = ws.dimensions

    ex = wb.create_sheet("Existing partners")
    ex.append(["Organization", "Status / Evidence"])
    for row in EXCLUDED:
        ex.append(list(row))
    ex.column_dimensions["A"].width = 60
    ex.column_dimensions["B"].width = 110
    for cell in ex[1]:
        cell.font = Font(bold=True)

    sm = wb.create_sheet("Summary")
    for row in SUMMARY:
        sm.append(list(row))
    sm.column_dimensions["A"].width = 38
    sm.column_dimensions["B"].width = 120
    for row in sm.iter_rows():
        if row[0].value and row[0].value.isupper():
            row[0].font = Font(bold=True, color="1F4E78")

    wb.save(path)


